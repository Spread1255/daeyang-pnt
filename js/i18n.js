  function getSavedLang() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved && LANGS.indexOf(saved) !== -1) {
        return saved;
      }
    } catch (e) {}
    return DEFAULT_LANG;
  }

  var currentLang = getSavedLang();

  function t(key) {
    var table = DICT[currentLang] || DICT[DEFAULT_LANG];
    if (table && Object.prototype.hasOwnProperty.call(table, key)) {
      return table[key];
    }
    var fallback = DICT[DEFAULT_LANG];
    return (fallback && fallback[key]) || key;
  }

  function forEachEl(root, selector, fn) {
    var list = root.querySelectorAll(selector);
    for (var i = 0; i < list.length; i++) {
      fn(list[i]);
    }
  }

  function applyStatic(root) {
    root = root || document;
    forEachEl(root, "[data-i18n]", function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    forEachEl(root, "[data-i18n-html]", function (el) {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    forEachEl(root, "[data-i18n-placeholder]", function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    forEachEl(root, "[data-i18n-aria-label]", function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
    });
    forEachEl(root, "[data-i18n-alt]", function (el) {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
    });
    forEachEl(root, "[data-i18n-content]", function (el) {
      el.setAttribute("content", t(el.getAttribute("data-i18n-content")));
    });
    document.documentElement.lang = currentLang;
  }

  function updatePressedState() {
    forEachEl(document, ".lang-switch button[data-lang]", function (btn) {
      var isCurrent = btn.getAttribute("data-lang") === currentLang;
      btn.setAttribute("aria-pressed", String(isCurrent));
    });
  }

  function setLang(lang) {
    if (LANGS.indexOf(lang) === -1) {
      return;
    }
    currentLang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
    applyStatic(document);
    updatePressedState();
    window.dispatchEvent(new CustomEvent("i18n:change", { detail: { lang: lang } }));
  }

  function buildSwitcher() {
    forEachEl(document, ".lang-switch button[data-lang]", function (btn) {
      btn.addEventListener("click", function () {
        setLang(btn.getAttribute("data-lang"));
      });
    });
    updatePressedState();
  }

  window.I18N = {
    t: t,
    lang: function () {
      return currentLang;
    },
    setLang: setLang,
    apply: applyStatic,
    seriesName: function (id) {
      return (SERIES_NAME[currentLang] || SERIES_NAME.ko)[id] || "";
    },
    colorName: function (code) {
      return (COLOR_NAME[currentLang] || COLOR_NAME.ko)[code] || "";
    },
    priceUse: function (id) {
      var lang = USE_LABEL[currentLang] || USE_LABEL.ko;
      return lang[USE_BY_ID[id]] || "";
    },
    priceFinish: function (id) {
      var lang = FINISH_LABEL[currentLang] || FINISH_LABEL.ko;
      return lang[FINISH_BY_ID[id]] || "";
    },
    priceInfo: function (id) {
      return (PRICE_INFO[currentLang] || PRICE_INFO.ko)[id] || "";
    }
  };

  function init() {
    applyStatic(document);
    buildSwitcher();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
